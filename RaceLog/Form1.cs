// ============================================================================
// RaceLog — Журнал тренировочных заездов (Windows Forms, .NET 10)
// ============================================================================
// Файл Form1.cs — основной код формы приложения.
// Здесь размещены:
//   - Константы (границы допустимого времени круга)
//   - Конструктор формы (инициализация + установка начальных значений)
//   - Обработчики кнопок: Добавить, Удалить выбранную, Очистить поля
//   - Вспомогательные методы: ClearInput() и ShowError()
// ============================================================================

namespace RaceLog
{
    /// <summary>
    /// Главная форма приложения «Журнал заездов».
    /// Наследуется от базового класса Form, который предоставляет
    /// стандартные возможности окна Windows.
    /// </summary>
    public partial class Form1 : Form
    {
        // ========================================================================
        // ПОСТОЯННЫЕ (константы) класса
        // ========================================================================
        // Константы объявлены на уровне класса, чтобы быть доступными
        // во всех методах формы. Ключевое слово const означает, что значение
        // задано при компиляции и не может быть изменено во время работы.

        /// <summary>
        /// Минимальное допустимое время учебного круга в секундах.
        /// Соответствует половине минуты (30 секунд).
        /// Значения меньше этой границы отклоняются.
        /// </summary>
        private const int MinLapSeconds = 30;

        /// <summary>
        /// Максимальное допустимое время учебного круга в секундах.
        /// Соответствует десяти минутам (600 секунд).
        /// Значения больше этой границы отклоняются.
        /// </summary>
        private const int MaxLapSeconds = 600;

        // ========================================================================
        // КОНСТРУКТОР ФОРМЫ
        // ========================================================================
        // Конструктор вызывается один раз при создании объекта формы (окна).
        // Сначала выполняется InitializeComponent — он создаёт все элементы
        // управления (кнопки, поля, списки), которые были размещены
        // в визуальном конструкторе Visual Studio.
        // После него мы задаём начальные значения для ComboBox.

        /// <summary>
        /// Конструктор формы. Вызывается при создании окна.
        /// Инициализирует компоненты и устанавливает начальные значения.
        /// </summary>
        public Form1()
        {
            // Метод автоматически создан конструктором форм Visual Studio.
            // Он создаёт и настраивает все элементы управления (кнопки,
            // поля ввода, списки и метки), размещённые в дизайнере формы.
            // Удалять этот вызов нельзя — без него форма будет пустой.
            InitializeComponent();

            // Установка первых вариантов в выпадающих списках.
            // SelectedIndex = 0 означает выбор первого элемента (Street и Учебный овал).
            // Важно: эти команды должны быть ПОСЛЕ InitializeComponent,
            // потому что элементы ComboBox заполняются именно в нём.
            cmbCar.SelectedIndex = 0;   // Первый автомобиль: Street
            cmbTrack.SelectedIndex = 0; // Первая трасса: Учебный овал
        }

        // ========================================================================
        // ОБРАБОТЧИК КНОПКИ «ДОБАВИТЬ»
        // ========================================================================
        // Этот метод вызывается при нажатии кнопки btnAdd (или клавиши Enter,
        // т.к. AcceptButton формы = btnAdd).
        // Он выполняет последовательную проверку введённых данных:
        //   1. Проверка имени пилота (не пустое)
        //   2. Проверка выбора автомобиля и трассы
        //   3. Проверка времени (целое число)
        //   4. Проверка диапазона времени (30–600 секунд)
        // Если все проверки пройдены — запись добавляется в список.

        /// <summary>
        /// Обработчик нажатия кнопки «Добавить».
        /// Читает данные из полей, проверяет их и добавляет запись в список.
        /// </summary>
        /// <param name="sender">Объект, вызвавший событие (кнопка btnAdd).</param>
        /// <param name="e">Данные события Click.</param>
        private void btnAdd_Click(object? sender, EventArgs e)
        {
            // ---- ШАГ 1: Чтение и проверка имени пилота ----
            // Считываем текст из поля txtDriver и убираем пробелы по краям
            // методом Trim(). Внутренние пробелы (между именем и фамилией) сохраняются.
            string driver = txtDriver.Text.Trim();

            // Если после Trim имя пустое (длина == 0), выводим ошибку
            // и завершаем обработчик через return. Список не изменяется.
            if (driver.Length == 0)
            {
                ShowError("Введите имя пилота");
                txtDriver.Focus(); // Возвращаем фокус в поле имени
                return;
            }

            // ---- ШАГ 2: Проверка выбора автомобиля и трассы ----
            // SelectedIndex < 0 означает, что ни один элемент не выбран.
            // Оператор || (логическое ИЛИ): если хотя бы один список без выбора — ошибка.
            if (cmbCar.SelectedIndex < 0 || cmbTrack.SelectedIndex < 0)
            {
                ShowError("Выберите автомобиль и трассу");
                return;
            }

            // ---- ШАГ 3: Преобразование времени и проверка формата ----
            // TextBox.Text всегда возвращает строку, даже если пользователь
            // ввёл число. Метод int.TryParse пытается преобразовать строку
            // в целое число. Возвращает true при успехе, false при неудаче.
            // Параметр out int seconds одновременно объявляет переменную
            // и передаёт её для записи результата.
            string timeText = txtTime.Text.Trim();
            bool valid = int.TryParse(timeText, out int seconds);

            // Если преобразование не удалось (введено «быстро», пусто, дробное число)
            if (!valid)
            {
                ShowError("Время должно быть целым числом");
                txtTime.Focus(); // Возвращаем фокус в поле времени
                return;
            }

            // ---- ШАГ 4: Проверка диапазона времени (30–600) ----
            // Значения на границах (30 и 600) принимаются.
            // Оператор || (ИЛИ): если время МЕНЬШЕ минимума ИЛИ БОЛЬШЕ максимума — ошибка.
            // НЕ используем && (И), потому что одновременное нарушение обеих
            // границ невозможно.
            if (seconds < MinLapSeconds || seconds > MaxLapSeconds)
            {
                ShowError($"Время должно быть от {MinLapSeconds} до {MaxLapSeconds} секунд");
                txtTime.Focus();
                return;
            }

            // ---- ШАГ 5: Все проверки пройдены — формируем строку записи ----
            // Интерполяция строк: символ $ перед кавычкой позволяет вставлять
            // значения переменных в строку через фигурные скобки {}.
            // Формат: «Имя | Автомобиль | Трасса | Время с»
            string record = $"{driver} | {cmbCar.Text} | {cmbTrack.Text} | {seconds} с";

            // Добавляем готовую строку в список результатов.
            // Items.Add добавляет элемент в конец коллекции ListBox.
            lstResults.Items.Add(record);

            // ---- ШАГ 6: Очистка полей ввода и обновление статуса ----
            // Вызываем вспомогательный метод очистки полей.
            ClearInput();

            // Показываем текущее количество записей в списке.
            // Items.Count содержит число элементов в ListBox.
            lblStatus.Text = $"Добавлено. Всего записей: {lstResults.Items.Count}";
        }

        // ========================================================================
        // ОБРАБОТЧИК КНОПКИ «УДАЛИТЬ ВЫБРАННУЮ»
        // ========================================================================
        // Этот метод вызывается при нажатии кнопки btnDelete.
        // Он удаляет из списка одну выбранную пользователем строку.
        // Если ничего не выбрано — выводит сообщение и не меняет список.

        /// <summary>
        /// Обработчик нажатия кнопки «Удалить выбранную».
        /// Удаляет из списка выбранный элемент.
        /// </summary>
        /// <param name="sender">Объект, вызвавший событие (кнопка btnDelete).</param>
        /// <param name="e">Данные события Click.</param>
        private void btnDelete_Click(object? sender, EventArgs e)
        {
            // Получаем индекс выбранного элемента в списке.
            // SelectedIndex возвращает -1, если ни одна строка не выбрана.
            int index = lstResults.SelectedIndex;

            // Проверяем: выбран ли вообще какой-либо элемент.
            // При index < 0 ничего не удаляем, а показываем сообщение.
            if (index < 0)
            {
                ShowError("Сначала выберите запись в списке");
                return;
            }

            // Удаляем элемент по его индексу.
            // Items.RemoveAt(index) удаляет строку по указанному номеру,
            // а не всегда первую строку. Индексы после удаления
            // пересчитываются автоматически.
            lstResults.Items.RemoveAt(index);

            // Обновляем сообщение в статусе с новым количеством записей.
            // Если список стал пустым, показываем соответствующее сообщение.
            if (lstResults.Items.Count > 0)
            {
                lblStatus.Text = $"Удалено. Всего записей: {lstResults.Items.Count}";
            }
            else
            {
                lblStatus.Text = "Список пуст";
            }
        }

        // ========================================================================
        // ОБРАБОТЧИК КНОПКИ «ОЧИСТИТЬ ПОЛЯ»
        // ========================================================================
        // Этот метод вызывается при нажатии кнопки btnClear.
        // Он очищает только поля ввода (имя, время) и возвращает первые варианты
        // в выпадающих списках. Результаты (ListBox) НЕ удаляются.

        /// <summary>
        /// Обработчик нажатия кнопки «Очистить поля».
        /// Сбрасывает поля ввода, сохраняя результаты в списке.
        /// </summary>
        /// <param name="sender">Объект, вызвавший событие (кнопка btnClear).</param>
        /// <param name="e">Данные события Click.</param>
        private void btnClear_Click(object? sender, EventArgs e)
        {
            // Вызываем общий метод очистки полей ввода.
            ClearInput();

            // Показываем сообщение о том, что поля очищены,
            // а результаты остались в списке.
            lblStatus.Text = "Поля очищены. Результаты сохранены в списке";
        }

        // ========================================================================
        // ВСПОМОГАТЕЛЬНЫЙ МЕТОД: Очистка полей ввода
        // ========================================================================
        // Этот метод используется в двух местах:
        //   1. После успешного добавления записи (btnAdd_Click)
        //   2. По кнопке «Очистить поля» (btnClear_Click)
        // Он очищает поля ввода и возвращает начальные значения,
        // но НЕ трогает список результатов lstResults.

        /// <summary>
        /// Очищает поля ввода (имя, время), возвращает первые варианты
        /// в выпадающих списках и устанавливает фокус на поле имени.
        /// Не затрагивает список результатов.
        /// </summary>
        private void ClearInput()
        {
            // Очищаем текстовые поля методом Clear().
            // Clear — это метод (действие), а не свойство.
            txtDriver.Clear();   // Удалить текст из поля имени
            txtTime.Clear();     // Удалить текст из поля времени

            // Возвращаем первые варианты в выпадающих списках.
            // SelectedIndex = 0 выбирает первый элемент (Street / Учебный овал).
            cmbCar.SelectedIndex = 0;
            cmbTrack.SelectedIndex = 0;

            // Передаём фокус клавиатуры полю ввода имени,
            // чтобы пользователь мог сразу начать вводить следующего пилота.
            txtDriver.Focus();
        }

        // ========================================================================
        // ВСПОМОГАТЕЛЬНЫЙ МЕТОД: Показать сообщение об ошибке
        // ========================================================================
        // Этот метод используется во всех местах, где обнаружена ошибка ввода.
        // Он принимает текст сообщения через параметр и выводит его в метку.
        // После вызова ShowError в обработчике нужен return для выхода.

        /// <summary>
        /// Выводит сообщение об ошибке в метку состояния lblStatus.
        /// </summary>
        /// <param name="message">Текст сообщения для пользователя.</param>
        private void ShowError(string message)
        {
            // Присваиваем переданный текст свойству Text метки lblStatus.
            // Метка отображает этот текст в нижней части формы.
            lblStatus.Text = message;
        }
    }
}
