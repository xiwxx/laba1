namespace RaceLog
{
    /// <summary>
    /// Главный класс приложения. Содержит точку входа — метод Main.
    /// </summary>
    internal static class Program
    {
        /// <summary>
        /// Главная точка входа в приложение.
        /// Инициализирует Windows Forms и запускает главную форму.
        /// </summary>
        [STAThread]
        static void Main()
        {
            // Инициализация Windows Forms: настройка визуальных стилей,
            // кодировки и прочих системных параметров.
            ApplicationConfiguration.Initialize();

            // Запуск главного окна приложения (Form1).
            // Метод Run блокирует выполнение до закрытия формы.
            Application.Run(new Form1());
        }
    }
}